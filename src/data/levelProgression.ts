// ============================================================================
// DYNAMIC ENDLESS LEVEL GENERATOR (Levels 21 to 100+ like Candy Crush!)
// Generates procedural levels deterministically based on level number
// ============================================================================

const LEVEL_CACHE = new Map<number, PathLevel>();

export function getLevelData(levelNumber: number): PathLevel {
  const safeLevelNum = Math.max(1, Math.floor(levelNumber));
  if (LEVEL_CACHE.has(safeLevelNum)) {
    return LEVEL_CACHE.get(safeLevelNum)!;
  }

  const meta = LEVEL_QUESTION_METADATA[safeLevelNum] || {
    questionTypeDescription: `Procedural dynamic challenge questions testing mixed US Civics, 50 States, Biology, Astronomy, and World History.`,
    topicTags: ['Endless Trail', 'Mixed Academy', 'Bonus Challenge', 'Civics & STEM'],
    difficultyTierLabel: 'Levels 21+: Endless',
  };

  // If it's within the crafted campaign (1 to 20), return it directly with meta
  if (safeLevelNum <= 20) {
    const found = CAMPAIGN_LEVELS.find(l => l.levelNumber === safeLevelNum);
    if (found) {
      const levelObj: PathLevel = {
        ...found,
        questions: found.questions.map(q => shuffleQuestionOptions(q)),
        questionTypeDescription: meta.questionTypeDescription,
        topicTags: meta.topicTags,
        difficultyTierLabel: meta.difficultyTierLabel,
      };
      LEVEL_CACHE.set(safeLevelNum, levelObj);
      return levelObj;
    }
  }

  // Endless Mode Procedural Generation for Level 21+
  const unitNumber = Math.floor((safeLevelNum - 1) / 5) + 1;
  const isMilestone = safeLevelNum % 5 === 0;
  const difficulty: LevelDifficulty = safeLevelNum > 35 ? 'master' : 'expert';

  // Seeded deterministic question picker from the pool
  const pool = GK_QUESTIONS;
  const startIndex = ((safeLevelNum * 7) % pool.length);
  const selectedQuestions: GKQuestion[] = [];

  for (let i = 0; i < 5; i++) {
    const qIndex = (startIndex + i * 3) % pool.length;
    const baseQ = pool[qIndex];
    selectedQuestions.push(shuffleQuestionOptions({
      ...baseQ,
      id: `endless_${safeLevelNum}_${i}`,
    }));
  }

  const titles = [
    'Cosmic Frontiers',
    'Global Statesmanship',
    'Deep Sea Exploration',
    'Quantum Wonders',
    'Universal Geography',
    'Historical Enigmas',
    'Planetary Mechanics',
    'Scientific Revolutions',
    'Master Mind Challenge',
    'Infinite Scholar Arena',
  ];
  const titleSeed = (safeLevelNum - 21) % titles.length;

  const result: PathLevel = {
    levelNumber: safeLevelNum,
    unit: unitNumber,
    unitTitle: `Unit ${unitNumber}: Endless Academy Trail`,
    title: `Level ${safeLevelNum}: ${titles[titleSeed]}`,
    subtitle: isMilestone ? 'Grand Milestone Mastery Challenge' : 'Dynamic Scholar Exploration',
    difficulty,
    category: 'mixed',
    curriculumGrade: `Level ${safeLevelNum} Mastery`,
    targetPassScore: 4,
    coinReward: isMilestone ? 40 : 25,
    isMilestone,
    milestoneRewardName: isMilestone ? `Level ${safeLevelNum} Mystery Treasure Chest` : undefined,
    questions: selectedQuestions,
    questionTypeDescription: meta.questionTypeDescription,
    topicTags: meta.topicTags,
    difficultyTierLabel: meta.difficultyTierLabel,
  };

  LEVEL_CACHE.set(safeLevelNum, result);
  return result;
}

// Helper to determine badge color by difficulty
export function getDifficultyColor(diff: LevelDifficulty): {
  badgeBg: string;
  badgeText: string;
  badgeBorder: string;
  nodeBg: string;
  nodeBorder: string;
} {
  switch (diff) {
    case 'easy':
      return {
        badgeBg: 'bg-emerald-50',
        badgeText: 'text-emerald-800',
        badgeBorder: 'border-emerald-200',
        nodeBg: 'from-emerald-500 to-teal-600',
        nodeBorder: 'border-emerald-700',
      };
    case 'medium':
      return {
        badgeBg: 'bg-blue-50',
        badgeText: 'text-blue-800',
        badgeBorder: 'border-blue-200',
        nodeBg: 'from-blue-600 to-indigo-600',
        nodeBorder: 'border-blue-800',
      };
    case 'hard':
      return {
        badgeBg: 'bg-amber-50',
        badgeText: 'text-amber-800',
        badgeBorder: 'border-amber-200',
        nodeBg: 'from-amber-500 to-orange-600',
        nodeBorder: 'border-amber-700',
      };
    case 'expert':
    case 'master':
    default:
      return {
        badgeBg: 'bg-purple-50',
        badgeText: 'text-purple-800',
        badgeBorder: 'border-purple-200',
        nodeBg: 'from-purple-600 to-pink-600',
        nodeBorder: 'border-purple-800',
      };
  }
}
